import ts from "typescript";
import { createRequire } from "node:module";

export const filesImpl = (root) => (excludes) => (includes) => () => ts.sys.readDirectory(root, undefined, excludes, includes);
export const importsImpl = (text) => () => ts.preProcessFile(text, true, true);
export const readConfigImpl = (path) => () => ts.readConfigFile(path, ts.sys.readFile);
export const parseConfigImpl = (config) => (root) => () => ts.parseJsonConfigFileContent(config, ts.sys, root);
export const resolveImpl = (name) => (file) => (options) => () => ts.resolveModuleName(name, file, options, ts.sys);
export const viteConfigImpl = (manifest) => (config) => () => createRequire(manifest)("vite").resolveConfig(config, "build", "production");
export const relayConfigImpl = (path) => () => createRequire(path)(path);
export const aliasPatternImpl = (alias) => () => alias.find.toString();
export const sourceImpl = (path) => (text) => () => ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
export const childrenImpl = (node) => () => node.getChildren();
export const sourceTextImpl = (node) => () => node.getText();
export const diagnosticsImpl = (node) => node.parseDiagnostics;
export const newExpressionImpl = ts.isNewExpression;
export const callExpressionImpl = ts.isCallExpression;
export const propertyAccessImpl = ts.isPropertyAccessExpression;
export const elementAccessImpl = ts.isElementAccessExpression;
export const metaPropertyImpl = ts.isMetaProperty;
export const identifierImpl = ts.isIdentifier;
export const stringLiteralImpl = ts.isStringLiteral;
export const importDeclarationImpl = ts.isImportDeclaration;
export const importClauseNodeImpl = ts.isImportClause;
export const expressionImpl = (node) => node.expression;
export const nameImpl = (node) => node.name;
export const valueImpl = (node) => node.text;
export const argumentsImpl = (node) => node.arguments;
export const keywordImpl = (node) => node.keywordToken;
export const importKeywordImpl = ts.SyntaxKind.ImportKeyword;
export const importClauseImpl = (node) => node.importClause;
export const moduleSpecifierImpl = (node) => node.moduleSpecifier;
export const typeOnlyImpl = (node) => node.isTypeOnly;
